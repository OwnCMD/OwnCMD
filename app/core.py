def acquire():
    now = time.time()
    with db() as c:
        c.begin_write()
        rows = c.execute(
            "SELECT * FROM tasks WHERE mode='work' AND status IN ('queued','running') AND control='ai' AND lease<%s AND busy<%s ORDER BY created LIMIT 50",
            (now, now),
        ).fetchall()
        for r in rows:
            s = state(r)
            if s.get("not_before", 0) > now:
                continue
            c.execute(
                "UPDATE tasks SET lease=%s,version=version+1,status='running' WHERE id=%s",
                (now + 180, r["id"]),
            )
            c.commit()
            d = dict(r)
            d.update(version=r["version"] + 1, lease=now + 180, status="running")
            return d
        c.commit()
    return None


def save(row, s, status="queued"):
    with db() as c:
        c.execute(
            "UPDATE tasks SET state=%s,status=CASE WHEN status IN ('cancelled','paused') THEN status ELSE %s END,lease=0,updated=%s WHERE id=%s AND version=%s",
            (enc(json.dumps(s)), status, time.time(), row["id"], row["version"]),
        )


def begin_action(task, actor, expected_epoch=None, workspace=False, browser_stop=False):
    with db() as c:
        c.begin_write()
        r = c.execute(
            "SELECT control,busy,status,control_epoch,lease FROM tasks WHERE id=%s",
            (task,),
        ).fetchone()
        if (
            browser_stop
            and r
            and (
                r["lease"] > time.time()
                or (r["control"] != "human" and r["status"] in ("queued", "running"))
            )
        ):
            raise ValueError(
                "OwnCMD has resumed work. Pause before closing the browser."
            )
        if (
            workspace
            and r
            and (
                r["lease"] > time.time()
                or r["status"] in ("queued", "running", "approval")
            )
        ):
            raise ValueError(
                "OwnCMD has resumed work. Pause before changing the workspace."
            )
        if expected_epoch is not None and r and r["control_epoch"] != expected_epoch:
            raise ValueError(
                "Browser control changed since this action was planned; inspect the current page"
            )
        if (
            not r
            or r["control"] != actor
            or r["busy"] > time.time()
            or r["status"] == "cancelled"
        ):
            raise ValueError("Browser control changed; action was not executed")
        c.execute("UPDATE tasks SET busy=%s WHERE id=%s", (time.time() + 140, task))
        c.commit()


def end_action(task):
    with db() as c:
        c.execute(
            "UPDATE tasks SET busy=0,control=CASE WHEN control='taking_over' THEN 'human' ELSE control END WHERE id=%s",
            (task,),
        )


def takeover(owner, task, actor):
    if actor not in ("human", "ai"):
        raise ValueError("Invalid control owner")
    with db() as c:
        c.begin_write()
        r = c.execute(
            "SELECT * FROM tasks WHERE id=%s AND owner=%s", (task, owner)
        ).fetchone()
        if not r:
            raise KeyError("Task not found")
        if actor == "ai" and r["busy"] > time.time():
            raise ValueError("Wait for the current action to finish")
        new = "taking_over" if actor == "human" and r["busy"] > time.time() else actor
        c.execute(
            "UPDATE tasks SET control=%s,control_epoch=control_epoch+1 WHERE id=%s",
            (new, task),
        )
        c.commit()
    event(task, "control", {"owner": new})
    return new


