def enc(s):
    return CIPHER.encrypt(str(s).encode()).decode()


def dec(s):
    return CIPHER.decrypt(s.encode()).decode() if s else ""


def ident():
    return str(uuid.uuid4())


def digest(s):
    return hashlib.sha256(s.encode()).hexdigest()


