def preferences(owner):
    with db() as c:
        r = c.execute(
            "SELECT body FROM preferences WHERE owner=%s", (owner,)
        ).fetchone()
    if not r:
        return dict(DEFAULT_PREFS)
    try:
        data = json.loads(dec(r["body"]))
    except Exception:
        data = {}
    return {**DEFAULT_PREFS, **{k: v for k, v in data.items() if k in DEFAULT_PREFS}}


def save_preferences(owner, prefs):
    clean = dict(DEFAULT_PREFS)
    clean.update({k: v for k, v in prefs.items() if k in DEFAULT_PREFS})
    with db() as c:
        c.execute(
            "INSERT INTO preferences(owner,body,updated) VALUES(%s,%s,%s) ON CONFLICT(owner) DO UPDATE SET body=excluded.body,updated=excluded.updated",
            (owner, enc(json.dumps(clean)), time.time()),
        )
    return clean


def initial_state(prompt, mode="work", images=None):
    model = (
        os.getenv("ASTER_WORK_MODEL", "openai/gpt-5.6-luna")
        if mode == "work"
        else os.getenv("ASTER_CHAT_MODEL", "google/gemini-3.5-flash-lite")
    )
    content = prompt
    if images:
        content = [{"type": "text", "text": prompt}] + images
    return {
        "messages": [{"role": "user", "content": content}],
        "result": "",
        "steps": 0,
        "attempts": 0,
        "searches": 0,
        "retry": 0,
        "not_before": 0,
        "pending": None,
        "tool_done": {},
        "sources": [],
        "browser_used": False,
        "completion_guard": "",
        "completion_retries": 0,
        "mode": mode,
        "model": model,
        "cost": 0,
    }


def create_task(
    owner,
    prompt,
    task_id=None,
    mode="work",
    images=None,
    temporary_chat=False,
    browser_display=None,
    skills_config=None,
    model_choice="auto",
    attachments=None,
):
    task_id = task_id or ident()
    uuid.UUID(task_id)
    if mode not in ("chat", "work"):
        raise ValueError("Mode must be chat or work")
    if not isinstance(prompt, str) or not 1 <= len(prompt) <= 24000:
        raise ValueError("Message must be 1–24,000 characters")
    from . import accounts

    policy = accounts.require(owner, mode)
    accounts.resolve_model(owner, mode, model_choice)
    now = time.time()
    s = initial_state(prompt, mode, images)
    s["model_choice"] = model_choice
    if browser_display is not None:
        s["browser_display"] = browser_display
    if mode == "work":
        from . import skills

        s["skills"] = skills.selection(owner, skills_config)
    if temporary_chat:
        if attachments:
            raise ValueError(
                "Documents require a saved conversation. Turn off temporary Chat."
            )
        if mode != "chat":
            raise ValueError("Temporary chat is only available in Chat mode")
        return temporary.create(owner, "tmp-" + task_id, enc(json.dumps(s)))
    with db() as c:
        c.begin_write()
        existing = c.execute(
            "SELECT owner FROM tasks WHERE id=%s", (task_id,)
        ).fetchone()
        if existing:
            if existing["owner"] != owner:
                raise ValueError("Task ID is unavailable")
            c.commit()
            return task_id
        # Chat conversations run synchronously in the API process and must never be
        # blocked by Work concurrency. For Work, only tasks that can consume worker
        # execution capacity count toward the limit; approval tasks are deliberately
        # excluded because they are paused waiting for the user.
        if mode == "work":
            count = c.execute(
                "SELECT count(*) FROM tasks WHERE owner=%s AND mode='work' AND status IN ('queued','running')",
                (owner,),
            ).fetchone()[0]
            if count >= policy["limits"]["active_work"]:
                raise ValueError(
                    "Finish or pause an executing Work task first (5 active Work task limit)"
                )
        status = "ready" if mode == "chat" else "queued"
        c.execute(
            "INSERT INTO tasks(id,owner,title,state,status,mode,created,updated) VALUES(%s,%s,%s,%s,%s,%s,%s,%s) ON CONFLICT DO NOTHING",
            (task_id, owner, prompt[:120], enc(json.dumps(s)), status, mode, now, now),
        )
        from . import documents

        documents.link(c, owner, task_id, attachments or [])
        from . import notebook

        notebook.seed(c, task_id, prompt)
        c.commit()
    event(
        task_id,
        "created",
        {
            "text": (
                "Conversation started."
                if mode == "chat"
                else "Work started; OwnCMD will choose the tools it needs automatically."
            ),
            "mode": mode,
        },
    )
    return task_id


